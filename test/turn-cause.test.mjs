// What started each turn (the usage rows' Cause): each cause from its message's words, a helper agent's replies in the
// turn they ran in, a report turn that ended in report_quiet, the lines that are not turns, and rows split by cause.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { turnCause, readSession, sessionRows, sessionLogFiles, CSV_COLUMNS, COORDINATION } from '../costs.mjs';

const ROOT = path.dirname(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')));
const PRICING = path.join(ROOT, 'pricing.json');
const T0 = new Date(2026, 9, 20, 10, 0, 0).getTime();
const at = (s) => new Date(T0 + s * 1000).toISOString();
let n = 0;
const usage = { input_tokens: 1000, output_tokens: 100 };
const msg = (s, text, extra = {}) => ({ type: 'user', uuid: `u${n++}`, timestamp: at(s), message: { role: 'user', content: [{ type: 'text', text }] }, ...extra });
const reply = (s, content = [{ type: 'text', text: 'ok' }]) => ({ type: 'assistant', uuid: `a${n++}`, requestId: `r${n}`, timestamp: at(s), message: { id: `m${n}`, model: 'claude-opus-5-5', content, usage } });
const result = (s, id) => ({ type: 'user', uuid: `t${n++}`, timestamp: at(s), message: { role: 'user', content: [{ type: 'tool_result', tool_use_id: id, content: 'done' }] } });
const tool = (id, name, input = {}) => ({ type: 'tool_use', id, name, input });

const REPORT = '<session-report>\nThese are reports from sessions you started.\n- "Fix it" finished: done.\n</session-report>';
const BRIEF = 'Fix the bug.(From Docket: This session was started by the session "Parent" (id 73d70e03-a8c1-452d-af08-d43574aced09) and is listed under it.)';
const SEND = 'Also add a test.\n\n(Sent by the session "Parent" in the portal, id 73d70e03-a8c1-452d-af08-d43574aced09)';

test('each cause from the words of the message that began the turn', () => {
  assert.equal(turnCause('please fix the login page'), 'person');
  assert.equal(turnCause(BRIEF), 'brief');
  assert.equal(turnCause(SEND), 'send');
  assert.equal(turnCause(REPORT), 'report');
  assert.equal(turnCause('(From Docket: the session "Child" now reports to you.)'), 'notice-coord');
  assert.equal(turnCause('(From Docket: the user started your proposal "Build X" as a session under this one.)'), 'notice-coord');
  assert.equal(turnCause('(From Docket: this session is near the point where it compacts. Write down your open items.)'), 'notice');
  assert.equal(turnCause('<task-notification><task-id>b1</task-id><status>completed</status></task-notification>'), 'task');
  // "(From Docket:" counts only at the start; a person quoting it is the person
  assert.equal(turnCause('what does "(From Docket: x reports to you)" mean?'), 'person');
  assert.deepEqual(COORDINATION, ['report', 'report-quiet', 'notice-coord']);
});

function session(lines, agentLines) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'turn-cause-'));
  const file = path.join(dir, 'S1.jsonl');
  fs.writeFileSync(file, lines.map((l) => JSON.stringify(l)).join('\n') + '\n');
  if (agentLines) {
    const sub = path.join(dir, 'S1', 'subagents');
    fs.mkdirSync(sub, { recursive: true });
    fs.writeFileSync(path.join(sub, 'agent-1.jsonl'), agentLines.map((l) => JSON.stringify({ ...l, isSidechain: true })).join('\n') + '\n');
  }
  return file;
}

const LINES = [
  msg(0, 'please fix the login page'),
  reply(10, [tool('b1', 'Bash')]), result(20, 'b1'), reply(30),
  msg(100, REPORT),
  reply(110, [tool('ag', 'Agent')]), result(400, 'ag'), reply(410), // a helper agent ran from 120s to 390s
  msg(500, REPORT),
  reply(510, [tool('q1', 'mcp__portal__report_quiet', { reason: 'news only' })]), result(515, 'q1'), reply(520),
  msg(600, REPORT),
  reply(610, [tool('q2', 'mcp__portal__report_quiet', { cancel: true })]), result(615, 'q2'), reply(620),
  msg(700, '<command-name>/model</command-name>'), // a local command: no new turn, so this reply stays in the report turn
  reply(705),
  msg(800, BRIEF), reply(810),
  msg(900, SEND), reply(910),
  msg(950, 'Caveat: the messages below were generated by the user while running local commands.', { isMeta: true }), reply(955),
  msg(1000, '(From Docket: the session "Child" now reports to you.)'), reply(1010),
  msg(1100, '(From Docket: this session is near the point where it compacts.)'), reply(1110),
  msg(1200, '<task-notification>done</task-notification>'), reply(1210),
  msg(1300, 'This session is being continued from a previous conversation.', { isCompactSummary: true }), reply(1310),
];
const AGENT = [msg(120, 'look into it'), reply(150), reply(390)];

test('replies take the cause of their turn; helper agents the main turn they ran in; report_quiet makes it report-quiet', () => {
  const file = session(LINES, AGENT);
  const { replies } = readSession(sessionLogFiles(file, 'S1'));
  const by = (s) => replies.find((r) => r.at === T0 + s * 1000).cause;
  assert.equal(by(10), 'person'); assert.equal(by(30), 'person');
  assert.equal(by(110), 'report'); assert.equal(by(410), 'report');
  assert.equal(by(150), 'report', 'a helper agent reply goes to the turn it ran in');
  assert.equal(by(390), 'report');
  assert.equal(by(510), 'report-quiet'); assert.equal(by(520), 'report-quiet', 'the whole turn, the call before report_quiet too');
  assert.equal(by(610), 'report', 'report_quiet with cancel is not quiet');
  assert.equal(by(705), 'report', 'a local command starts no turn');
  assert.equal(by(810), 'brief'); assert.equal(by(910), 'send');
  assert.equal(by(955), 'send', 'a meta line starts no turn');
  assert.equal(by(1010), 'notice-coord'); assert.equal(by(1110), 'notice'); assert.equal(by(1210), 'task');
  assert.equal(by(1310), 'task', 'a compact summary starts no turn');
});

test('a reply before any message has no cause', () => {
  const { replies } = readSession([session([reply(0), msg(10, 'hi'), reply(20)])]);
  assert.deepEqual(replies.map((r) => r.cause), ['', 'person']);
});

test('rows are per session, day, agent, model and cause, and add up to the same cost', () => {
  const file = session(LINES, AGENT);
  const rows = sessionRows('c', file, 'S1', PRICING, 'T', {});
  assert.ok(rows.every((r) => 'Cause' in r));
  const key = (r) => `${r.Source}|${r.Cause}`;
  assert.equal(new Set(rows.map((r) => `${r.Date}|${r.Model}|${key(r)}`)).size, rows.length, 'one row per day, source, model and cause');
  const cost = (f) => rows.filter(f).reduce((a, r) => a + r.Cost, 0);
  assert.ok(cost((r) => r.Source === 'agent' && r.Cause === 'report') > 0, 'the helper agent row is a report row');
  assert.equal(rows.filter((r) => r.Source === 'main' && r.Cause === 'report-quiet')[0].Turns, 2);
  assert.equal(rows.find((r) => r.Source === 'main' && r.Cause === 'report').Turns, 5);
  // the old shape: the same replies, all on one row per day, source and model
  const all = rows.reduce((a, r) => a + r.Cost, 0);
  const replies = readSession(sessionLogFiles(file, 'S1')).replies.length;
  assert.equal(rows.reduce((a, r) => a + r.Turns, 0), replies);
  assert.ok(all > 0 && Math.abs(all - cost(() => true)) < 1e-9);
  assert.equal(rows.filter((r) => r.Agents).length, 1, 'per-session counts stay on one row');
  assert.equal(CSV_COLUMNS.at(-1), 'Cause', 'the new column goes last, so readers by position still work');
  assert.equal(CSV_COLUMNS.at(-2), 'Connection');
});
